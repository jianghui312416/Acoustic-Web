test('global globe mounts AIS markers with hover halo and a compact synchronized contact card', () => {
  assert.match(view, /import AisGlobalOverlay from '@\/components\/ais\/AisGlobalOverlay\.vue'/)
  assert.match(view, /<AisGlobalOverlay/)
  assert.match(view, /v-if="viewerReady && aisMonitorState\.displayEnabled"/)
  assert.match(view, /:active="viewMode === 'globe' && !terrainLeaving"/)
  assert.match(overlay, /new Cesium\.BillboardCollection/)
  assert.match(overlay, /Cesium\.Cartesian3\.fromDegrees/)
  assert.match(overlay, /Cesium\.ScreenSpaceEventType\.MOUSE_MOVE/)
  assert.match(overlay, /function haloImage/)
  assert.match(overlay, /class="ais-contact-card"/)
  assert.match(overlay, /selectAisVessel\(vessel, 'globe'\)/)
  assert.match(overlay, /onBeforeUnmount\(\(\) => \{[\s\S]*destroyLayer\(\)/)
  assert.match(overlay, /const viewer = layerViewer/)
  assert.match(overlay, /viewer\.scene\.primitives\.remove\(billboardCollection\)/)
  assert.match(overlay, /viewer\.scene\?\.requestRender\?\.\(\)/)
  assert.match(overlay, /props\.viewer\?\.scene\?\.requestRender\?\.\(\)/)
  assert.doesNotMatch(overlay, /class="ais-overlay"/)
  assert.doesNotMatch(overlay, />全球 AIS</)
})

